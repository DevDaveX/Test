const assert=require('node:assert/strict');
const {reasons,pick,weight}=require('./core.js');
const f={buy:'owned',budget:15,genre:'all',duration:999,verified:true,horror:false,queueExclude:true};
const base={id:'1',multiplayer:true,owners:['b','c'],confirmed:true,genre:'Horror',minutes:60,price:10,priceSource:'manual',votes:['neutral','neutral']};
assert.deepEqual(reasons(base,f,[]),[]);
assert(reasons({...base,owners:['a']},f,[]).length);
assert.deepEqual(reasons({...base,owners:['a']},{...f,buy:'one'},[]),[]);
assert(reasons({...base,owners:[]},{...f,buy:'one'},[]).includes('Beide müssten kaufen'));
assert.deepEqual(reasons({...base,owners:[]},{...f,buy:'both'},[]),[]);
assert(reasons({...base,owners:['a'],price:null},{...f,buy:'one'},[]).includes('Kaufpreis unbekannt / veraltet'));
assert(reasons({...base,owners:['a'],price:15.01},{...f,buy:'one'},[]).includes('Über Budget pro Person'));
assert(reasons({...base,owners:['a'],priceAt:0,priceSource:'steam'},{...f,buy:'one'},[]).length);
assert(reasons({...base,votes:['yes','no']},f,[]).includes('Heute nicht gewünscht'));
assert(reasons(base,{...f,horror:true},[]).includes('Horror ausgeschlossen'));
assert(reasons({...base,confirmed:false},f,[]).includes('Eignung zu zweit unbestätigt'));
assert(reasons({...base,minutes:null},{...f,duration:60},[]).includes('Spielzeit zu lang / unbekannt'));
assert(reasons(base,f,[{id:'1'}]).includes('Bereits in Warteschlange'));
assert.equal(weight({...base,votes:['yes','yes']},true),4);
const pool=[base,{...base,id:'2',votes:['yes','yes']}];
assert.equal(pick([],true,()=>0),null);
assert.equal(pick(pool,true,()=>0).id,'1');
for(let i=1;i<5;i++)assert.equal(pick(pool,true,()=>i).id,'2');
assert.equal(pick(pool,false,()=>1).id,'2');
console.log('19 assertions passed: ownership union, budget, veto, eligibility, time, queue and weighted draw.');

assert(reasons({...base,multiplayer:false},f,[]).includes('Kein bestätigtes Koop-/Mehrspielerspiel'));
const huntsman={...base,id:'extra-huntsman',mode:'stream',owners:['c'],votes:['no','yes']};
assert.deepEqual(reasons(huntsman,f,[]),[]);
assert.equal(weight(huntsman,true),2);
assert(reasons({...huntsman,votes:['yes','no']},f,[]).includes('Heute nicht gewünscht'));
console.log('Singleplayer exclusion and Pia-only livestream rules passed.');

const {jointlyOwned,purchaseReasons}=require('./core.js');
assert.equal(jointlyOwned({...base,owners:['a','b']}),false);
assert.equal(jointlyOwned({...base,owners:['b','c']}),true);
const offer={...base,owners:['a'],price:15,confirmed:false};
assert.deepEqual(purchaseReasons(offer,f,[]),[]);
for(const g of [{...offer,price:15.01},{...offer,owners:[]},{...offer,owners:['a','c']},{...offer,price:null},{...offer,votes:['yes','no']},{...offer,removed:true},{...offer,multiplayer:false},{...offer,priceAt:0,priceSource:'steam'}])assert(purchaseReasons(g,{...f,budget:100},[]).length);
assert(purchaseReasons({...offer,mode:'stream'},f,[]).length);
console.log('Shared-ownership and single-missing-copy purchase rules passed, including hard 15 EUR limit.');
